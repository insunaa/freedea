#!/usr/bin/env python3
"""Generate src/ui/LicenseTexts.h: verbatim license texts for the on-device
Licenses viewer (WORKPLAN 6.4), embedded as flash (DROM) string constants.

Sources were verified against the bundled or upstream license files on
2026-09-09 (see the WORKPLAN 6.4 entry). Re-running requires only the staged
upstream snapshots tracked under tools/licenses/ plus the vendored files, so
the output stays reproducible on a fresh clone.

Usage: python3 bin/gen_license_texts.py
"""

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "ui" / "LicenseTexts.h"


def read(rel: str) -> str:
    return (ROOT / rel).read_text(encoding="utf-8").replace("\r\n", "\n")


def block_comment(text: str, marker: str) -> str:
    """Extract the first /* ... */ comment block containing `marker`,
    de-commented. Blocks are matched individually so a preceding unrelated
    comment never joins the extraction."""
    for m in re.finditer(r"/\*.*?\*/", text, re.S):
        if marker in m.group(0):
            return _decomment(m.group(0)[2:-2])
    raise SystemExit(f"no comment block containing {marker!r}")


def _decomment(body: str) -> str:
    lines = []
    for line in body.split("\n"):
        line = line.strip()
        if line.startswith("*"):
            line = line[1:]
        lines.append(line.strip())
    return "\n".join(lines).strip()


def apache_block_from_mbedtls() -> str:
    """mbedTLS LICENSE = dual-license statement + Apache-2.0 + GPL-2.0 text.
    Keep the statement and the Apache part (the option Freedea uses); point at
    upstream for the omitted GPL alternative."""
    raw = read("tools/licenses/mbedtls-LICENSE.txt")
    head = re.split(r"\n={10,}\n", raw)[0].strip()
    return head + (
        "\n\n(Note: the GPL-2.0-or-later alternative text is omitted here;"
        " see the full upstream LICENSE file.)"
    )


CLIMAPILOT = """climapilot (reference only)

Freedea does not link, copy, or bundle any code from climapilot. It is listed
because design questions about the Midea LAN protocol were cross-checked
against this project.

No LICENSE file is published upstream (checked via the GitHub API on
2026-09-09), so no SPDX identifier is claimed here.

Source: https://github.com/pit711/climapilot"""


def main() -> None:
    texts = [
        ("kFreedea", read("LICENSE").strip()),
        ("kApache20", read("tools/licenses/esp-idf-LICENSE.txt").strip()),
        ("kArduinoLgpl", read("tools/licenses/arduino-LICENSE.md").strip()),
        ("kFreeink", read("tools/licenses/freeink-LICENSE.txt").strip()),
        ("kQrcodegen", block_comment(read("lib/QrCode/src/qrcodegen.h"), "Permission is hereby granted")),
        ("kMbedtls", apache_block_from_mbedtls()),
        ("kLwipBsd", block_comment(read("tools/licenses/lwip-init.c"), "Redistribution and use")),
        ("kMideaMsmart", read("tools/licenses/midea-LICENSE.md").strip()),
        # Vendored source (7.3): reproducible straight from the checkout.
        ("kWireGuardBsd3", read("lib/WireGuard/LICENSE").strip()),
        # Icon assets (9.1): ISC, plus the Feather-derived MIT subset the file
        # itself lists (we use lock, monitor, moon, target from it).
        # https://github.com/lucide-icons/lucide raw LICENSE @ a79b2d1.
        ("kLucideIcons", read("tools/licenses/lucide-LICENSE.txt").strip()),
        ("kClimapilotNotice", CLIMAPILOT),
    ]

    parts = [
        "#pragma once\n",
        "// Generated by bin/gen_license_texts.py -- do not edit.\n"
        "// Verbatim license texts for the on-device Licenses viewer (WORKPLAN 6.4),\n"
        "// kept as flash (DROM) constants: zero DRAM footprint, readable offline.\n\n"
        "namespace lic {\n",
    ]
    for sym, text in texts:
        if (")LICF" in text) or ("\x00" in text):
            raise SystemExit(f"{sym}: raw-string delimiter collision")
        parts.append(f'\ninline constexpr char {sym}[] = R"LICF({text}\n)LICF";\n')
    parts.append("\n}  // namespace lic\n")

    OUT.write_text("".join(parts), encoding="utf-8")
    total = sum(len(t.encode()) for _, t in texts)
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes, {total} bytes of text)")


if __name__ == "__main__":
    sys.exit(main())
